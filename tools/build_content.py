#!/usr/bin/env python3
"""Builds the bundled content JSON and the Supabase seed from tools/content/*.py.
Run:  python3 tools/build_content.py   (add --check-links to verify every source URL)
"""
import json, os, sys, collections, urllib.request
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "content"))
import challenges, vocabulary, micro, cards_a, cards_b, cards_c

RES = os.path.join(ROOT, "Packages/TwelveCore/Sources/TwelveCore/Resources")
cards = cards_a.CARDS + cards_b.CARDS + cards_c.CARDS
counts = collections.Counter()
problems = []
for c in cards:
    counts[c["category"]] += 1
    c["id"] = f'{c["category"]}-{counts[c["category"]]:03d}'
    n = len(c["body"].split())
    if not 50 <= n <= 120: problems.append(f'{c["id"]}: {n} words')
    if not c["sourceURL"].startswith("https://"): problems.append(f'{c["id"]}: bad source')
    if c["quiz"] and not (0 <= c["quiz"]["answer"] < len(c["quiz"]["options"])): problems.append(f'{c["id"]}: bad quiz')
    if not c["quiz"] and not c["prompt"]: problems.append(f'{c["id"]}: no interaction')
for cat, n in sorted(counts.items()):
    print(f"{cat:12s} {n}")
    if n < 20: problems.append(f"{cat}: only {n} cards")
if len({c["headline"] for c in cards}) != len(cards): problems.append("duplicate headline")

# Quiz answers are authored with the correct option first; shuffle deterministically
# so the right answer is not always the first button.
import random
for c in cards:
    if c["quiz"]:
        rng = random.Random(c["id"])
        opts = c["quiz"]["options"]; right = opts[c["quiz"]["answer"]]
        rng.shuffle(opts); c["quiz"]["answer"] = opts.index(right)

if "--check-links" in sys.argv:
    for url in sorted({c["sourceURL"] for c in cards}):
        try:
            req = urllib.request.Request(url, method="GET", headers={"User-Agent": "content-link-check/1.0"})
            code = urllib.request.urlopen(req, timeout=20).status
        except Exception as e:
            code = getattr(e, "code", str(e))
        if code != 200: problems.append(f"link {code}: {url}")

if problems:
    print("\n".join(problems)); sys.exit(1)

def dump(name, obj):
    with open(os.path.join(RES, name + ".json"), "w") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
dump("challenges", challenges.CHALLENGES)
dump("vocabulary", vocabulary.LANGUAGES)
dump("micro", micro.MICRO)
dump("discoveries", cards)

def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"
def j(o):
    return q(json.dumps(o, ensure_ascii=False)) + "::jsonb"
os.makedirs(os.path.join(ROOT, "supabase/seed"), exist_ok=True)
with open(os.path.join(ROOT, "supabase/seed/content_seed.sql"), "w") as f:
    f.write("-- Generated by tools/build_content.py. Do not edit by hand.\n")
    for c in challenges.CHALLENGES:
        f.write("insert into public.challenge_definitions (id, year, month, title, category, story, instructions, completion_target, unit, module_type, metric, entry_kind, minimum_amount, reveal_at, accessible_alternatives, editorial, editorial_version) values ("
                f"{q(c['id'])}, {c['year']}, {c['month']}, {q(c['title'])}, {q(c['category'])}, {q(c['story'])}, {j(c['instructions'])}, {c['target']}, {q(c['unit'])}, {q(c['module'])}, {q(c['metric'])}, {q(c['entryKind'])}, {c['minimumAmount'] if c['minimumAmount'] is not None else 'null'}, "
                f"make_timestamptz({c['year']}, {c['month']}, 1, 0, 0, 0, 'Pacific/Kiritimati'), {j(c['accessibleAlternative'])}, {j(c)}, {c['version']}) "
                "on conflict (id) do update set title = excluded.title, story = excluded.story, instructions = excluded.instructions, editorial = excluded.editorial, editorial_version = excluded.editorial_version "
                "where public.challenge_definitions.reveal_at > now();\n")
    for c in cards:
        f.write("insert into public.discovery_cards (id, headline, content, category, subcategory, source_title, source_url, interaction, content_version, status) values ("
                f"{q(c['id'])}, {q(c['headline'])}, {q(c['body'])}, {q(c['category'])}, {q(c['subcategory'])}, {q(c['sourceTitle'])}, {q(c['sourceURL'])}, {j({'quiz': c['quiz'], 'prompt': c['prompt'], 'evergreen': c['evergreen']})}, {c['version']}, 'published') "
                "on conflict (id) do update set headline = excluded.headline, content = excluded.content, source_title = excluded.source_title, source_url = excluded.source_url, interaction = excluded.interaction, content_version = excluded.content_version;\n")
print("ok:", len(cards), "cards")
